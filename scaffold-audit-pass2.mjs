async function writeAll() {
  let created = 0;
  let skipped = 0;

  for (const [rel, content] of Object.entries(FILES)) {
    const full = join(ROOT, rel);
    if (await exists(full)) {
      skipped++;
      continue;
    }
    await mkdir(dirname(full), { recursive: true });
    await writeFile(full, content, "utf8");
    created++;
    console.log("  + " + rel);
  }

  console.log("");
  console.log("Done. " + created + " file(s) created, " + skipped + " skipped (already exist).");
}

writeAll().catch((err) => {
  console.error(err);
  process.exit(1);
});